import { describe, it, expect } from 'vitest';
import {
  preprocessAndParseSyllabusJson,
  decodeHtmlEntities,
} from '../src/utils/syllabusJsonSanitizer';

describe('Syllabus JSON Preprocessor & HTML Entity Sanitizer', () => {
  it('safely decodes HTML entities like &#x20;, &quot;, &nbsp;, and &amp;', () => {
    expect(decodeHtmlEntities('&#x20;&quot;Thermodynamics&quot;&#x20;&nbsp;&lt;Unit 1&gt;')).toBe(
      ' "Thermodynamics"  <Unit 1>'
    );
  });

  it('resolves the position 1 error when text starts with {&#x20;"schemaVersion": 1', () => {
    // Exact bug reported in Issue 2: ChatGPT output with &#x20; right after {
    const rawWithEntityAtPos1 = `{&#x20;"schemaVersion":&#x20;1,
  "subject": {
    "name": "Organic Chemistry I",
    "chapters": [
      {
        "name": "Alkanes and Cycloalkanes",
        "estimatedLectures": 6,
        "importance": "High",
        "topics": [
          { "name": "Conformations of Ethane and Butane", "importance": "High" }
        ]
      }
    ]
  }
}`;

    const parsed = preprocessAndParseSyllabusJson(rawWithEntityAtPos1);
    expect(parsed).toBeDefined();
    expect(parsed.schemaVersion).toBe(1);
    expect(parsed.subject.name).toBe('Organic Chemistry I');
    expect(parsed.subject.chapters[0].name).toBe('Alkanes and Cycloalkanes');
    expect(parsed.subject.chapters[0].topics[0].name).toBe('Conformations of Ethane and Butane');
  });

  it('handles markdown code fences with surrounding commentary and line-continuation backslashes', () => {
    const chatGptOutput = `Here is your requested syllabus extracted from the PDF:

\`\`\`json \\
{
  "schemaVersion": 1,
  "subject": {
    "name": "Fluid Mechanics",
    "chapters": [
      {
        "name": "Bernoulli Equation & Continuity",
        "estimatedLectures": 4,
        "importance": "Medium",
        "topics": [
          { "name": "Incompressible Flow", "importance": "Medium" }
        ]
      }
    ]
  }
}
\`\`\`

Let me know if you need any adjustments!`;

    const parsed = preprocessAndParseSyllabusJson(chatGptOutput);
    expect(parsed.subject.name).toBe('Fluid Mechanics');
    expect(parsed.subject.chapters[0].name).toBe('Bernoulli Equation & Continuity');
  });

  it('preserves valid JSON content, escape sequences, and formulas without silent alteration', () => {
    const validJsonWithMathAndQuotes = JSON.stringify({
      schemaVersion: 1,
      subject: {
        name: 'Mathematics III: ODEs & Fourier Series',
        chapters: [
          {
            name: 'Linear 2nd Order ODEs (e.g. y" + ay\' + by = 0)',
            estimatedLectures: 5,
            importance: 'High',
            topics: [
              { name: 'Homogeneous with Constant Coefficients: r^2 + ar + b = 0' },
              { name: 'Method of Undetermined Coefficients & "Variation of Parameters"' },
            ],
          },
        ],
      },
    }, null, 2);

    const parsed = preprocessAndParseSyllabusJson(validJsonWithMathAndQuotes);
    expect(parsed.subject.name).toBe('Mathematics III: ODEs & Fourier Series');
    expect(parsed.subject.chapters[0].name).toContain('y" + ay\' + by = 0');
    expect(parsed.subject.chapters[0].topics[1].name).toContain('"Variation of Parameters"');
  });

  it('throws a helpful, clean error message when the input is completely empty or corrupted', () => {
    expect(() => preprocessAndParseSyllabusJson('')).toThrow(
      /Please paste the JSON syllabus generated by ChatGPT/i
    );
    expect(() => preprocessAndParseSyllabusJson('This is just random text with no JSON at all')).toThrow(
      /Invalid JSON format/i
    );
  });
});

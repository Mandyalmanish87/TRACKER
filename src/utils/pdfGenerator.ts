/**
 * Escapes characters for PDF string literals: ( ) and \
 */
function escapePdfText(str: string): string {
  return str
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)')
    .replace(/[\r\n\t]/g, ' ');
}

/**
 * Wraps text into lines that fit within a specified character length.
 */
function wrapText(text: string, maxCharsPerLine: number = 75): string[] {
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let currentLine = '';

  for (const word of words) {
    if (!currentLine) {
      currentLine = word;
    } else if ((currentLine + ' ' + word).length <= maxCharsPerLine) {
      currentLine += ' ' + word;
    } else {
      lines.push(currentLine);
      currentLine = word;
    }
  }

  if (currentLine) {
    lines.push(currentLine);
  }

  return lines;
}

/**
 * Generates a valid standard PDF 1.4 binary string for Lecture Study Notes.
 */
export function generateStudyNotesPdfBytes(notes: LectureStudyNotes): Uint8Array {
  // Page size: Letter 612 x 792 pt, margins 54pt (0.75in)
  const margin = 54;
  let y = 740;
  const bottomMargin = 50;
  const pageHeight = 792;

  interface StreamCommand {
    font: 'bold' | 'regular';
    size: number;
    text: string;
    x: number;
    y: number;
  }

  const pages: StreamCommand[][] = [[]];
  let currentPage = 0;

  function ensureSpace(heightNeeded: number) {
    if (y - heightNeeded < bottomMargin) {
      currentPage++;
      pages[currentPage] = [];
      y = 740;
    }
  }

  function addLine(text: string, font: 'bold' | 'regular', size: number, indent: number = 0, spacingAfter: number = 6) {
    ensureSpace(size + spacingAfter);
    pages[currentPage].push({
      font,
      size,
      text,
      x: margin + indent,
      y,
    });
    y -= (size + spacingAfter);
  }

  function addParagraph(text: string, font: 'bold' | 'regular', size: number, indent: number = 0, spacingAfter: number = 8) {
    const lines = wrapText(text, 72 - Math.floor(indent / 7));
    for (let i = 0; i < lines.length; i++) {
      const isLast = i === lines.length - 1;
      addLine(lines[i], font, size, indent, isLast ? spacingAfter : 3);
    }
  }

  // Header Banner
  addLine('STUDENT TRACKER — EDUHUB LECTURE STUDY NOTES', 'bold', 10, 0, 14);
  addLine(notes.lectureTitle, 'bold', 18, 0, 6);
  addLine(`Course: ${notes.courseTitle}`, 'bold', 12, 0, 4);
  addLine(`Source: ${notes.sourceUrl}`, 'regular', 9, 0, 4);
  addLine(`Date Generated: ${new Date(notes.generatedAt).toLocaleDateString()} · Confidential & Local`, 'regular', 9, 0, 16);

  // Section 1: Summary
  addLine('1. EXECUTIVE STUDY SUMMARY', 'bold', 13, 0, 6);
  addParagraph(notes.summary, 'regular', 10, 10, 14);

  // Section 2: Key Concepts
  if (notes.keyConcepts && notes.keyConcepts.length > 0) {
    addLine('2. KEY CONCEPTS & THEORETICAL PRINCIPLES', 'bold', 13, 0, 6);
    notes.keyConcepts.forEach((concept, idx) => {
      addLine(`• Concept ${idx + 1}: ${concept.title}`, 'bold', 10, 8, 3);
      addParagraph(concept.description, 'regular', 9.5, 16, 8);
    });
    y -= 6;
  }

  // Section 3: Definitions
  if (notes.definitions && notes.definitions.length > 0) {
    addLine('3. CORE DEFINITIONS & VOCABULARY', 'bold', 13, 0, 6);
    notes.definitions.forEach((def) => {
      addLine(`[DEF] ${def.term}`, 'bold', 10, 8, 3);
      addParagraph(def.definition, 'regular', 9.5, 16, 8);
    });
    y -= 6;
  }

  // Section 4: Formulas and Rules
  if (notes.formulasOrRules && notes.formulasOrRules.length > 0) {
    addLine('4. FORMULAS, EQUATIONS & OPERATIONAL RULES', 'bold', 13, 0, 6);
    notes.formulasOrRules.forEach((f) => {
      addLine(`→ ${f.name}:`, 'bold', 10, 8, 3);
      addParagraph(f.rule, 'regular', 9.5, 16, 8);
    });
    y -= 6;
  }

  // Footer on each page
  pages.forEach((pageCmds, pIdx) => {
    pageCmds.push({
      font: 'regular',
      size: 8,
      text: `Page ${pIdx + 1} of ${pages.length} — Generated by Student Tracker EduHub`,
      x: margin,
      y: 30,
    });
  });

  // Build PDF 1.4 Object Structure
  let out = '%PDF-1.4\n%\xE2\xE3\xCF\xD3\n';
  const offsets: number[] = [];

  function recordObject(objNum: number, content: string) {
    offsets[objNum] = out.length;
    out += `${objNum} 0 obj\n${content}\nendobj\n`;
  }

  // 1: Catalog
  recordObject(1, '<< /Type /Catalog /Pages 2 0 R >>');

  // Page Object Numbers: 3, 4, ...
  // Content Object Numbers: 3 + numPages, 3 + numPages + 1, ...
  const numPages = pages.length;
  const pageObjectIds = Array.from({ length: numPages }, (_, i) => 3 + i);
  const contentObjectIds = Array.from({ length: numPages }, (_, i) => 3 + numPages + i);
  const fontRegularId = 3 + 2 * numPages;
  const fontBoldId = 3 + 2 * numPages + 1;

  // 2: Pages Root
  recordObject(
    2,
    `<< /Type /Pages /Kids [${pageObjectIds.map((id) => `${id} 0 R`).join(' ')}] /Count ${numPages} >>`
  );

  // Each Page Object
  pages.forEach((_, i) => {
    recordObject(
      pageObjectIds[i],
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 ${pageHeight}] /Resources << /Font << /F1 ${fontRegularId} 0 R /F2 ${fontBoldId} 0 R >> >> /Contents ${contentObjectIds[i]} 0 R >>`
    );
  });

  // Each Content Stream
  pages.forEach((cmds, i) => {
    let streamText = '';
    cmds.forEach((cmd) => {
      const fontCode = cmd.font === 'bold' ? '/F2' : '/F1';
      streamText += `BT ${fontCode} ${cmd.size} Tf ${cmd.x.toFixed(2)} ${cmd.y.toFixed(2)} Td (${escapePdfText(cmd.text)}) Tj ET\n`;
    });

    const streamLength = streamText.length;
    recordObject(
      contentObjectIds[i],
      `<< /Length ${streamLength} >>\nstream\n${streamText}endstream`
    );
  });

  // Fonts: Helvetica and Helvetica-Bold
  recordObject(fontRegularId, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>');
  recordObject(fontBoldId, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>');

  const xrefOffset = out.length;
  const totalObjects = 3 + 2 * numPages + 2;

  out += `xref\n0 ${totalObjects}\n0000000000 65535 f \n`;
  for (let i = 1; i < totalObjects; i++) {
    const off = String(offsets[i] || 0).padStart(10, '0');
    out += `${off} 00000 n \n`;
  }

  out += `trailer\n<< /Size ${totalObjects} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

  // Convert ASCII to Uint8Array
  const bytes = new Uint8Array(out.length);
  for (let i = 0; i < out.length; i++) {
    bytes[i] = out.charCodeAt(i) & 0xff;
  }
  return bytes;
}

/**
 * Triggers a direct file download of the generated PDF in the browser.
 */
export function downloadStudyNotesPdf(notes: LectureStudyNotes, customFilename?: string): void {
  const bytes = generateStudyNotesPdfBytes(notes);
  const blob = new Blob([bytes.buffer as ArrayBuffer], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);

  const safeTitle = (notes.lectureTitle || 'Lecture_Notes')
    .replace(/[^a-zA-Z0-9_-]/g, '_')
    .substring(0, 40);
  const filename = customFilename || `${safeTitle}_Study_Notes.pdf`;

  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);

  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/**
 * Fallback browser print layout for instant preview or direct paper/PDF printing.
 */
export function printStudyNotesHtml(notes: LectureStudyNotes): void {
  const printWindow = window.open('', '_blank');
  if (!printWindow) return;

  const content = `
<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>${notes.lectureTitle} — Study Notes</title>
  <style>
    body {
      font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif;
      line-height: 1.6;
      color: #1a1a1a;
      max-width: 800px;
      margin: 40px auto;
      padding: 0 20px;
    }
    h1 { font-size: 24px; margin-bottom: 4px; color: #0f172a; }
    h2 { font-size: 16px; margin-top: 24px; margin-bottom: 8px; border-bottom: 1px solid #e2e8f0; padding-bottom: 4px; color: #334155; }
    .meta { font-size: 13px; color: #64748b; margin-bottom: 24px; }
    .concept { margin-bottom: 12px; }
    .concept-title { font-weight: bold; color: #1e293b; }
    .def-box { background: #f8fafc; border-left: 3px solid #0284c7; padding: 8px 12px; margin-bottom: 8px; font-size: 14px; }
    .formula-box { background: #fdf2f8; border-left: 3px solid #db2777; padding: 8px 12px; margin-bottom: 8px; font-family: monospace; }
    @media print {
      body { margin: 20px; }
      @page { margin: 1.5cm; }
    }
  </style>
</head>
<body>
  <h1>${notes.lectureTitle}</h1>
  <div class="meta">
    <div><strong>Course:</strong> ${notes.courseTitle}</div>
    <div><strong>Source:</strong> ${notes.sourceUrl}</div>
    <div><strong>Generated:</strong> ${new Date(notes.generatedAt).toLocaleString()}</div>
  </div>

  <h2>1. Summary</h2>
  <p>${notes.summary}</p>

  ${notes.keyConcepts.length > 0 ? `
    <h2>2. Key Concepts</h2>
    ${notes.keyConcepts.map(c => `
      <div class="concept">
        <div class="concept-title">• ${c.title}</div>
        <div>${c.description}</div>
      </div>
    `).join('')}
  ` : ''}

  ${notes.definitions.length > 0 ? `
    <h2>3. Definitions</h2>
    ${notes.definitions.map(d => `
      <div class="def-box">
        <strong>${d.term}:</strong> ${d.definition}
      </div>
    `).join('')}
  ` : ''}

  ${notes.formulasOrRules.length > 0 ? `
    <h2>4. Formulas & Rules</h2>
    ${notes.formulasOrRules.map(f => `
      <div class="formula-box">
        <strong>${f.name}:</strong> ${f.rule}
      </div>
    `).join('')}
  ` : ''}

  <script>
    window.onload = function() {
      window.print();
    };
  </script>
</body>
</html>
  `;

  printWindow.document.write(content);
  printWindow.document.close();
}
